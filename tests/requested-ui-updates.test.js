import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { freshLibrary, nextIdeaName, saveRecord, validateLibrary } from '../src/demo/storage.js'
import { composeIdea } from '../src/demo/domain.js'
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8')
const app=read('../src/demo-main.jsx'),native=read('../android/app/src/main/java/com/ideaassist/app/MainActivity.kt')
const idea=()=>composeIdea({categoryId:'food',words:['딸기','자전거','구름'],condition:'작게 시작하기'})
test('default saved names are numbered, skip existing numbers and keep explicit names on resave',()=>{
  let library=freshLibrary()
  assert.equal(nextIdeaName(library.ideas),'새 아이디어 1')
  const first=idea()
  library=saveRecord(library,first,{name:'',folderId:'default'})
  assert.equal(library.ideas[0].name,'새 아이디어 1')
  library=saveRecord(library,idea(),{name:'',folderId:'default'})
  assert.equal(library.ideas[0].name,'새 아이디어 2')
  library=saveRecord(library,first,{name:'내가 정한 이름',folderId:'default'})
  library=saveRecord(library,first,{name:'',folderId:'default'})
  assert.equal(library.ideas[0].name,'내가 정한 이름'); assert.equal(library.ideas.length,2)
  assert.equal(nextIdeaName([{name:'새 아이디어 8'},{name:'새 아이디어 3'}]),'새 아이디어 9')
  assert.equal(nextIdeaName([{name:'새 아이디어 '+'9'.repeat(70)}]),'새 아이디어 1')
})
test('legacy generated test titles migrate only by exact signature and validation is idempotent',()=>{
  let library=saveRecord(freshLibrary(),idea(),{name:'직접 주제 검증 · 규칙 abc123',folderId:'default'})
  library=saveRecord(library,idea(),{name:'사용자 제목',folderId:'default'})
  const migrated=validateLibrary(library)
  assert.equal(migrated.ideas[0].name,'사용자 제목')
  assert.equal(migrated.ideas[1].name,'새 아이디어 1')
  assert.equal(library.ideas[1].name,'직접 주제 검증 · 규칙 abc123')
  assert.deepEqual(validateLibrary(migrated),migrated)
})
test('development selection is not generation; only confirmation executes it',()=>{
  assert.match(app,/onClick=\{\(\) => setSelectedDirection\(d.id\)\}/)
  assert.match(app,/selectedDirection && <button[^>]+onClick=\{\(\) => runGeneration\('develop', \{ direction: selectedDirection \}\)\}/)
  assert.match(app,/>이 방식으로 다듬기</)
  assert.match(native,/selectedDirection=id/)
  assert.match(native,/button\(confirmation,"이 방식으로 다듬기",true\)/)
  assert.doesNotMatch(native,/button\(row,title\) \{ generate\("develop",id\)/)
})
test('every generated result removes combination backlink; redundant cloud block and old fallback wording are gone',()=>{
  const result=app.slice(app.indexOf("{screen === 'result' &&"),app.indexOf("{screen === 'elaborate' &&"))
  assert.doesNotMatch(result,/<Back|단어 조합/)
  const nativeResult=native.slice(native.indexOf('private fun resultScreen()'),native.indexOf('private fun elaborateScreen()'))
  assert.ok(nativeResult.includes('session.current'))
  assert.doesNotMatch(nativeResult,/‹ 단어 조합/)
  assert.match(app,/screen === 'custom'.*<Back/)
  assert.match(native,/textAction\(body, "‹ 단어 조합"\) \{ go\("words"\) \}/)
  assert.doesNotMatch(native,/오류 시 규칙 결과로 자동 대체하지 않습니다|클라우드 연결 설정/)
  assert.match(native,/오류 시 임의 결과로 자동 대체하지 않습니다/)
  const settings=read('../src/EngineSettings.jsx')
  assert.doesNotMatch(settings,/클라우드 연결 설정/)
  assert.equal((settings.match(/<b>클라우드 AI<\/b>/g)||[]).length,1)
  const popup=read('../src/TopicPicker.jsx')
  assert.match(popup,/aria-label="선택지로 돌아가기"/)
  assert.doesNotMatch(popup,/>선택지로 돌아가기<\/button>/)
})
